#!/usr/bin/env node
// ===================================================================
// Generate migrations/supabase-migrations.js from SQL files
// ===================================================================
// Reads all migrations/*.sql files, extracts the version from the
// filename (e.g. 1.099_enable_realtime.sql → '1.099'), and writes
// a single JS module exporting SUPABASE_MIGRATIONS keyed by version.
//
// Usage: node scripts/generate-supabase-migrations.js
// ===================================================================

const fs = require('fs');
const path = require('path');

const migDir = path.join(__dirname, '..', 'migrations');
const outFile = path.join(migDir, 'supabase-migrations.js');

// Collect all .sql files, sorted by version
const sqlFiles = fs.readdirSync(migDir)
  .filter(f => f.endsWith('.sql'))
  .sort((a, b) => {
    const va = parseFloat(a.split('_')[0]);
    const vb = parseFloat(b.split('_')[0]);
    return va - vb;
  });

if (sqlFiles.length === 0) {
  console.error('No .sql files found in migrations/');
  process.exit(1);
}

// Build entries
const entries = [];
for (const file of sqlFiles) {
  const version = file.split('_')[0]; // e.g. '1.099'
  const sql = fs.readFileSync(path.join(migDir, file), 'utf8');
  // Escape backticks and backslashes for JS template literals
  const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`');
  entries.push(`  '${version}': \`${escaped}\``);
}

const output = `// ===================================================================
// SUPABASE MIGRATIONS — embedded SQL for the schema-banner modal
// ===================================================================
// AUTO-GENERATED by scripts/generate-supabase-migrations.js
// Do not edit by hand — edit the .sql files in migrations/ instead.
// ===================================================================

const SUPABASE_MIGRATIONS = {
${entries.join(',\n\n')},
};

export { SUPABASE_MIGRATIONS };
`;

fs.writeFileSync(outFile, output);
console.log(`Generated ${outFile} — ${sqlFiles.length} migration(s): ${sqlFiles.map(f => f.split('_')[0]).join(', ')}`);
